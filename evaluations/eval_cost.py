# 8. STATISTICS HELPERS
# ============================================================

def successful_rows(rows):
    """Return only successful benchmark runs."""

    return [
        row
        for row in rows
        if row["status"] == "OK"
    ]


def average(rows, key):
    """Calculate arithmetic mean."""

    values = [
        row[key]
        for row in rows
    ]

    if not values:
        return 0

    return sum(values) / len(values)


def percentile(values, p):
    """
    Calculate percentile using linear interpolation.
    """

    if not values:
        return 0

    values = sorted(values)

    if len(values) == 1:
        return values[0]

    position = (len(values) - 1) * p / 100

    lower = int(position)

    upper = min(
        lower + 1,
        len(values) - 1,
    )

    fraction = position - lower

    return (
        values[lower]
        + (values[upper] - values[lower])
        * fraction
    )


