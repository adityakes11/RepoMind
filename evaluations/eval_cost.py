# 9. REPORT
# ============================================================

def report(rows):
    """Print aggregate cost report."""

    successful = successful_rows(rows)

    if not successful:
        print()
        print("No successful runs were recorded.")
        return

    n = len(successful)

    # --------------------------------------------------------
    # Token statistics
    # --------------------------------------------------------

    avg_input = average(
        successful,
        "input",
    )

    avg_output = average(
        successful,
        "output",
    )

    avg_cached = average(
        successful,
        "cached",
    )

    total_input = sum(
        row["input"]
        for row in successful
    )

    total_output = sum(
        row["output"]
        for row in successful
    )

    total_cached = sum(
        row["cached"]
        for row in successful
    )

    # --------------------------------------------------------
    # Cost statistics
    # --------------------------------------------------------

    costs = [
        row["cost_total"]
        for row in successful
    ]

    avg_cost = average(
        successful,
        "cost_total",
    )

    min_cost = min(costs)

    max_cost = max(costs)

    p50_cost = percentile(
        costs,
        50,
    )

    p95_cost = percentile(
        costs,
        95,
    )

    p99_cost = percentile(
        costs,
        99,
    )

    # --------------------------------------------------------
    # Input/output cost split
    # --------------------------------------------------------

    avg_input_cost = (
        average(successful, "cost_input")
        + average(successful, "cost_cached")
    )

    avg_output_cost = average(
        successful,
        "cost_output",
    )

    total_avg_cost = (
        avg_input_cost
        + avg_output_cost
    )

    if total_avg_cost > 0:

        input_share = (
            avg_input_cost
            / total_avg_cost
            * 100
        )

        output_share = (
            avg_output_cost
            / total_avg_cost
            * 100
        )

    else:

        input_share = 0
        output_share = 0

    # --------------------------------------------------------
    # Cache share
    # --------------------------------------------------------

    if avg_input > 0:

        cache_share = (
            avg_cached
            / avg_input
            * 100
        )

    else:

        cache_share = 0

    # --------------------------------------------------------
    # Projection
    # --------------------------------------------------------

    daily_cost = (
        avg_cost
        * QUERIES_PER_DAY
    )

    monthly_cost = (
        daily_cost
        * 30
    )

    # --------------------------------------------------------
    # Budget
    # --------------------------------------------------------

    budget_verdict = (
        "PASS"
        if avg_cost <= COST_BUDGET_PER_QUERY_USD
        else "FAIL"
    )

    # ========================================================
    # PRINT REPORT
    # ========================================================

    print()
    print()
    print("=" * 70)
    print("COST EVALUATION REPORT")
    print("=" * 70)

    print()
    print("RUN SUMMARY")
    print("-" * 70)

    print(
        f"samples                 : {n}"
    )

    print(
        f"successful              : {n}"
    )

    print(
        f"failed                  : {len(rows) - n}"
    )

    print()
    print("TOKEN USAGE")
    print("-" * 70)

    print(
        f"avg input tokens        : {avg_input:10.0f}"
    )

    print(
        f"avg output tokens       : {avg_output:10.0f}"
    )

    print(
        f"avg cached tokens       : {avg_cached:10.0f}"
    )

    print(
        f"cache share             : {cache_share:10.2f}%"
    )

    print()

    print(
        f"total input tokens      : {total_input:10,d}"
    )

    print(
        f"total output tokens     : {total_output:10,d}"
    )

    print(
        f"total cached tokens     : {total_cached:10,d}"
    )

    print()
    print("THEORETICAL COST")
    print("-" * 70)

    print(
        f"input price / 1M        : ${PRICE_INPUT_PER_1M:.4f}"
    )

    print(
        f"cached input / 1M       : ${PRICE_CACHED_INPUT_PER_1M:.4f}"
    )

    print(
        f"output price / 1M       : ${PRICE_OUTPUT_PER_1M:.4f}"
    )

    print()

    print(
        f"avg cost / query        : "
        f"${avg_cost:.6f}"
        f"   (Rs {avg_cost * USD_TO_INR:.4f})"
    )

    print(
        f"p50 cost / query        : "
        f"${p50_cost:.6f}"
    )

    print(
        f"p95 cost / query        : "
        f"${p95_cost:.6f}"
    )

    print(
        f"p99 cost / query        : "
        f"${p99_cost:.6f}"
    )

    print(
        f"min / max cost          : "
        f"${min_cost:.6f} / "
        f"${max_cost:.6f}"
    )

    print()

    print(
        f"cost split              : "
        f"{input_share:.0f}% input / "
        f"{output_share:.0f}% output"
    )

    print()
    print("BUSINESS PROJECTION")
    print("-" * 70)

    print(
        f"queries / day           : "
        f"{QUERIES_PER_DAY:,}"
    )

    print(
        f"estimated / day         : "
        f"${daily_cost:.2f}"
        f"   (Rs {daily_cost * USD_TO_INR:.2f})"
    )

    print(
        f"estimated / month      : "
        f"${monthly_cost:.2f}"
        f"   (Rs {monthly_cost * USD_TO_INR:.2f})"
    )

    print()
    print("COST BUDGET")
    print("-" * 70)

    print(
        f"budget / query          : "
        f"${COST_BUDGET_PER_QUERY_USD:.6f}"
    )

    print(
        f"measured average        : "
        f"${avg_cost:.6f}"
    )

    print(
        f"budget verdict          : "
        f"[{budget_verdict}]"
    )

    print()
    print("=" * 70)

    print(
        "IMPORTANT:"
    )

    print(
        "RepoMind currently uses a local Ollama model."
    )

    print(
        "Therefore the values above are theoretical provider-cost "
        "estimates, not an actual Ollama bill."
    )

    print(
        "If RepoMind is moved to a hosted API, update the pricing "
        "constants before using the projection for budgeting."
    )

    print("=" * 70)


