"""
Operational evaluation: COST

RepoMind cost evaluation.

Cost is derived from:

    cost = input_tokens * input_price
         + cached_input_tokens * cached_input_price
         + output_tokens * output_price

IMPORTANT:
RepoMind currently uses a local Ollama model, so this is NOT an actual
Ollama bill. It is a theoretical unit-cost estimate based on the number
of tokens generated by the pipeline and the configured provider prices.

The evaluator uses the REAL RepoMind retrieval pipeline and the REAL
prompt construction path.

Pipeline flow:

    Question
       |
       v
    Retriever
       |
       v
    Retrieved documents
       |
       v
    build_prompt()
       |
       v
    Ollama LLM
       |
       v
    AIMessage / response metadata
       |
       v
    Token counts
       |
       v
    Estimated cost

Token sources:

1. LangChain usage_metadata, when available.
2. Ollama response_metadata, when available.

For Ollama, the commonly available fields are:

    prompt_eval_count -> input/prompt tokens
    eval_count        -> output/generated tokens

Cached tokens are usually not available from local Ollama responses,
so cached tokens default to 0.

This evaluator intentionally does NOT use RAGPipeline.run(), because
that method converts the model response into a normal string and may
discard token usage metadata.
"""

