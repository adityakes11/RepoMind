def main():

    global QUERIES_PER_DAY
    global COST_BUDGET_PER_QUERY_USD

    args = parse_args()

    QUERIES_PER_DAY = args.queries_per_day

    COST_BUDGET_PER_QUERY_USD = args.budget

    print()
    print("Initializing RepoMind pipeline...")

    pipeline = RAGPipeline()

    rows = benchmark(
        pipeline=pipeline,
        collection_name=args.collection,
        top_k=args.top_k,
        repeats=args.repeats,
    )

    report(rows)


