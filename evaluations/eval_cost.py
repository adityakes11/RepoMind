# 10. ARGUMENT PARSER
# ============================================================

def parse_args():
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(
        description=(
            "Measure RepoMind token usage and "
            "estimate theoretical LLM cost."
        )
    )

    parser.add_argument(
        "--collection",
        required=True,
        help="Chroma collection name.",
    )

    parser.add_argument(
        "--top-k",
        type=int,
        default=DEFAULT_TOP_K,
        help=(
            f"Number of documents to retrieve. "
            f"Default: {DEFAULT_TOP_K}"
        ),
    )

    parser.add_argument(
        "--repeats",
        type=int,
        default=REPEATS,
        help=(
            f"Number of repetitions per question. "
            f"Default: {REPEATS}"
        ),
    )

    parser.add_argument(
        "--queries-per-day",
        type=int,
        default=QUERIES_PER_DAY,
        help=(
            f"Expected daily query volume. "
            f"Default: {QUERIES_PER_DAY}"
        ),
    )

    parser.add_argument(
        "--budget",
        type=float,
        default=COST_BUDGET_PER_QUERY_USD,
        help=(
            "Maximum theoretical cost per query in USD."
        ),
    )

    return parser.parse_args()


