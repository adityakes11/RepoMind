# Cost is only a theoretical estimate for the current local Ollama setup.
#
# These values can be changed if you want to estimate the cost as if the
# same workload were executed against a hosted provider.

REPEATS = 3

PRICE_INPUT_PER_1M = 0.15

PRICE_CACHED_INPUT_PER_1M = 0.075

PRICE_OUTPUT_PER_1M = 0.60


# Business projection
QUERIES_PER_DAY = 2000

# Approximate conversion rate.
USD_TO_INR = 88.0


# Maximum acceptable theoretical cost per query.
COST_BUDGET_PER_QUERY_USD = 0.0015


# Default RepoMind retrieval configuration.
DEFAULT_TOP_K = 3


# ============================================================
# 4. TOKEN EXTRACTION
# ============================================================

def extract_token_usage(message):
    """
    Extract token usage from a LangChain AIMessage.

    Supports both:

    1. LangChain usage_metadata
    2. Ollama response_metadata

    Returns:

        {
            "input": int,
            "output": int,
            "cached": int
        }
    """

    input_tokens = 0
    output_tokens = 0
    cached_tokens = 0

    # --------------------------------------------------------
    # First try LangChain usage_metadata
    # --------------------------------------------------------

    usage = getattr(message, "usage_metadata", None)

    if usage:
        input_tokens = (
            usage.get("input_tokens")
            or usage.get("prompt_tokens")
            or 0
        )

        output_tokens = (
            usage.get("output_tokens")
            or usage.get("completion_tokens")
            or 0
        )

        input_details = usage.get("input_token_details") or {}

        cached_tokens = (
            input_details.get("cache_read")
            or input_details.get("cached_tokens")
            or 0
        )

    # --------------------------------------------------------
    # If usage_metadata is unavailable, try response_metadata
    # --------------------------------------------------------

    response_metadata = getattr(message, "response_metadata", None) or {}

    if not input_tokens:
        input_tokens = (
            response_metadata.get("prompt_eval_count")
            or response_metadata.get("prompt_tokens")
            or 0
        )

    if not output_tokens:
        output_tokens = (
            response_metadata.get("eval_count")
            or response_metadata.get("completion_tokens")
            or 0
        )

    # Ollama/local models generally do not expose provider-level
    # cached token billing information.
    if not cached_tokens:
        cached_tokens = (
            response_metadata.get("cache_read")
            or response_metadata.get("cached_tokens")
            or 0
        )

    return {
        "input": int(input_tokens),
        "output": int(output_tokens),
        "cached": int(cached_tokens),
    }


# ============================================================
# 5. COST CALCULATION
# ============================================================

def calculate_cost(
    input_tokens,
    output_tokens,
    cached_tokens,
):
    """
    Calculate theoretical USD cost.

    Formula:

        uncached input
            @ PRICE_INPUT_PER_1M

        cached input
            @ PRICE_CACHED_INPUT_PER_1M

        output
            @ PRICE_OUTPUT_PER_1M
    """

    uncached_input = max(
        input_tokens - cached_tokens,
        0,
    )

    input_cost = (
        uncached_input
        / 1_000_000
        * PRICE_INPUT_PER_1M
    )

    cached_cost = (
        cached_tokens
        / 1_000_000
        * PRICE_CACHED_INPUT_PER_1M
    )

    output_cost = (
        output_tokens
        / 1_000_000
        * PRICE_OUTPUT_PER_1M
    )

    total_cost = (
        input_cost
        + cached_cost
        + output_cost
    )

    return {
        "input": input_cost,
        "cached": cached_cost,
        "output": output_cost,
        "total": total_cost,
    }


# ============================================================
# 6. TOKEN MEASUREMENT
# ============================================================

def measure_tokens(
    pipeline,
    question,
    collection_name,
    top_k,
):
    """
    Run the real RepoMind retrieval + prompt + LLM pipeline.

    We intentionally stop before RAGPipeline.run() returns the final
    dictionary so that we can inspect the raw AIMessage and its token
    metadata.
    """

    # --------------------------------------------------------
    # Step 1: Retrieve real repository context
    # --------------------------------------------------------

    documents = pipeline.retriever(
        question,
        collection_name,
        top_k,
    )

    if not documents:
        return {
            "input": 0,
            "output": 0,
            "cached": 0,
            "documents": 0,
            "status": "NO_DOCUMENTS",
        }

    # --------------------------------------------------------
    # Step 2: Build the exact RepoMind prompt
    # --------------------------------------------------------

    prompt = build_prompt(
        question,
        documents,
    )

    # --------------------------------------------------------
    # Step 3: Use the same LLM configured in RepoMind
    # --------------------------------------------------------

    llm = pipeline.generator.llm

    # Invoke the actual model.
    message = llm.invoke(prompt)

    # --------------------------------------------------------
    # Step 4: Extract token usage
    # --------------------------------------------------------

    tokens = extract_token_usage(message)

    return {
        "input": tokens["input"],
        "output": tokens["output"],
        "cached": tokens["cached"],
        "documents": len(documents),
        "status": "OK",
    }


# ============================================================
# 7. BENCHMARK
# ============================================================

def benchmark(
    pipeline,
    collection_name,
    top_k,
    repeats,
):
    """
    Run the cost benchmark.

    Cost is much more stable than latency, so a small number of
    repetitions is normally sufficient.
    """

    rows = []

    total_runs = len(QUESTIONS) * repeats

    print("=" * 70)
    print("RepoMind COST Evaluation")
    print("=" * 70)

    print(f"Questions       : {len(QUESTIONS)}")
    print(f"Repeats         : {repeats}")
    print(f"Total runs      : {total_runs}")
    print(f"Collection      : {collection_name}")
    print(f"Top-k           : {top_k}")

    print()
    print("Measuring token usage...")
    print()

    run_number = 0

    for question in QUESTIONS:

        for repeat in range(repeats):

            run_number += 1

            try:

                token_data = measure_tokens(
                    pipeline=pipeline,
                    question=question,
                    collection_name=collection_name,
                    top_k=top_k,
                )

                if token_data["status"] != "OK":

                    rows.append({
                        "question": question,
                        "input": 0,
                        "output": 0,
                        "cached": 0,
                        "documents": token_data["documents"],
                        "cost_input": 0,
                        "cost_cached": 0,
                        "cost_output": 0,
                        "cost_total": 0,
                        "status": token_data["status"],
                    })

                    print(
                        f"[{run_number:02d}/{total_runs}] "
                        f"NO DOCUMENTS | {question}"
                    )

                    continue

                cost = calculate_cost(
                    input_tokens=token_data["input"],
                    output_tokens=token_data["output"],
                    cached_tokens=token_data["cached"],
                )

                row = {
                    "question": question,

                    "input": token_data["input"],
                    "output": token_data["output"],
                    "cached": token_data["cached"],

                    "documents": token_data["documents"],

                    "cost_input": cost["input"],
                    "cost_cached": cost["cached"],
                    "cost_output": cost["output"],
                    "cost_total": cost["total"],

                    "status": "OK",
                }

                rows.append(row)

                print(
                    f"[{run_number:02d}/{total_runs}] "
                    f"in={token_data['input']:5d} "
                    f"out={token_data['output']:5d} "
                    f"cached={token_data['cached']:5d} "
                    f"cost=${cost['total']:.6f}"
                )

            except Exception as exc:

                rows.append({
                    "question": question,

                    "input": 0,
                    "output": 0,
                    "cached": 0,

                    "documents": 0,

                    "cost_input": 0,
                    "cost_cached": 0,
                    "cost_output": 0,
                    "cost_total": 0,

                    "status": f"ERROR: {exc}",
                })

                print(
                    f"[{run_number:02d}/{total_runs}] "
                    f"ERROR: {exc}"
                )

    return rows


